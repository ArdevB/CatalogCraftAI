import { Router } from 'express';
import { z } from 'zod';
import { bulkReviewSchema, exportRequestSchema, objectIdSchema, reviewActionSchema } from '@catalogcraft/shared';
import { getAuth, requireAuth, requirePermission } from '../../middleware/require-auth.js';
import type { FileStorage } from '../../services/storage/storage.js';
import { sendSuccess } from '../../utils/http-response.js';
import { validateRequest } from '../../utils/validate-request.js';
import { listJobActivity } from '../audit/audit.service.js';
import { getJob } from '../catalog-jobs/catalog-job.service.js';
import { toRowDto } from '../catalog-rows/catalog-row.service.js';
import { createExport, downloadExport, getExport, listJobExports, toExportDtos } from '../exports/export.service.js';
import { bulkReview, reviewSuggestion } from './review.service.js';

const jobParams = z.object({ jobId: objectIdSchema });
const rowParams = z.object({ jobId: objectIdSchema, rowId: objectIdSchema });
const exportParams = z.object({ exportId: objectIdSchema });

/** Mounted under /jobs: review decisions, activity and exports of one job. */
export function reviewRouter(storage: FileStorage): Router {
  const router = Router();
  router.use(requireAuth);
  const canReview = requirePermission('suggestions:review');

  router.patch('/:jobId/rows/:rowId', canReview, async (req, res) => {
    const { params, body } = validateRequest(req, { params: rowParams, body: reviewActionSchema });
    const row = await reviewSuggestion(getAuth(req), params.jobId, params.rowId, body);
    sendSuccess(res, toRowDto(row), { message: 'Suggestion updated.' });
  });

  router.post('/:jobId/approve', canReview, async (req, res) => {
    const { params, body } = validateRequest(req, { params: jobParams, body: bulkReviewSchema });
    const updated = await bulkReview(getAuth(req), params.jobId, 'approve', body);
    sendSuccess(res, { updated }, { message: `${updated} suggestion${updated === 1 ? '' : 's'} approved.` });
  });

  router.post('/:jobId/reject', canReview, async (req, res) => {
    const { params, body } = validateRequest(req, { params: jobParams, body: bulkReviewSchema });
    const updated = await bulkReview(getAuth(req), params.jobId, 'reject', body);
    sendSuccess(res, { updated }, { message: `${updated} suggestion${updated === 1 ? '' : 's'} rejected.` });
  });

  router.get('/:jobId/activity', requirePermission('audit:read'), async (req, res) => {
    const { params } = validateRequest(req, { params: jobParams });
    await getJob(getAuth(req), params.jobId); // 404 for other organizations' jobs
    sendSuccess(res, await listJobActivity(getAuth(req), params.jobId));
  });

  router.post('/:jobId/export', requirePermission('exports:create'), async (req, res) => {
    const { params, body } = validateRequest(req, { params: jobParams, body: exportRequestSchema });
    const record = await createExport(storage, getAuth(req), params.jobId, body);
    const [dto] = await toExportDtos([record]);
    sendSuccess(res, dto, { status: 201, message: 'Export ready.' });
  });

  router.get('/:jobId/exports', requirePermission('jobs:read'), async (req, res) => {
    const { params } = validateRequest(req, { params: jobParams });
    sendSuccess(res, await listJobExports(getAuth(req), params.jobId));
  });

  return router;
}

/** Mounted under /exports. Every download is authorised and logged. */
export function exportsRouter(storage: FileStorage): Router {
  const router = Router();
  router.use(requireAuth);

  router.get('/:exportId', requirePermission('jobs:read'), async (req, res) => {
    const { params } = validateRequest(req, { params: exportParams });
    const [dto] = await toExportDtos([await getExport(getAuth(req), params.exportId)]);
    sendSuccess(res, dto);
  });

  router.get('/:exportId/download', requirePermission('jobs:read'), async (req, res) => {
    const { params } = validateRequest(req, { params: exportParams });
    const { record, data } = await downloadExport(storage, getAuth(req), params.exportId);
    // The stored filename is generated by us (letters, digits, dashes), but encode it anyway.
    const asciiName = record.filename.replace(/[^\w.-]/g, '_');
    res.setHeader('Content-Type', 'text/csv; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${asciiName}"; filename*=UTF-8''${encodeURIComponent(record.filename)}`);
    res.setHeader('Cache-Control', 'private, no-store');
    res.send(data);
  });

  return router;
}
